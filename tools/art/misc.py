# ---------- items (16x16) ----------
def pick(head):
    hi,lo=head; c=Cv(16,16)
    c.line(3,13,11,5,'c'); c.line(4,13,12,5,'b')
    c.grid(6,1,['..'+hi*3+'...', '.'+hi+hi+lo+hi+hi+'..', hi+hi+lo+'..'+lo+hi+'.', hi+lo+'.....'+lo+hi, hi+'.......'+hi])
    return c
for name,head in [('wood',('d','c')),('copper',('q','p')),('bronze',('Y','y')),('iron',('v','u')),('silver',('W','v')),('aqua',('E','D')),('crystal',('J','H')),('ember',('T','S')),('heart',('z','Y'))]:
    write('items','pick-'+name,[pick(head)])
def bar(hi,mid,lo):
    c=Cv(16,16)
    c.grid(1,5,['...'+hi*9+'..', '..'+hi+mid*8+lo+'..', '.'+hi+mid*9+lo+'.', hi+mid*10+lo+lo, lo*14])
    c.px(4,6,'W' if hi not in 'WE' else 'E')
    return c
for name,cols in [('copper',('q','p','o')),('tin',('W','v','u')),('bronze',('Y','y','o')),('iron',('v','u','t')),('silver',('W','E','v')),('gold',('z','Y','y'))]:
    write('items','bar-'+name,[bar(*cols)])
def chunk(a,b,rock=('u','t','s')):
    c=Cv(16,16); r1,r2,r3=rock
    c.grid(2,4,['...'+r1*5+'...', '..'+r1+r2*6+r3+'..', '.'+r1+r2*8+r3+'.', r1+r2*10+r3, r1+r2*10+r3, '.'+r2*10+r3, '..'+r3*9+'.'])
    for (x,y) in [(5,6),(9,7),(7,9),(11,9)]: c.px(x,y,a); c.px(x+1,y,b)
    return c
